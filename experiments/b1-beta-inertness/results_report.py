"""B1: generate RESULTS.md from runs/b1-beta-inertness/ledger.json.

    .venv/bin/python experiments/b1-beta-inertness/results_report.py

Every number is read from the ledger (the key is named in each table); nothing is typed.
"""

# ruff: noqa: B023 -- every closure below is called by per_seed() inside the same
# loop iteration that defines it, so late binding cannot occur.
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from rsr.exit_codes import Exit, did_not_run, run_main  # noqa: E402

LEDGER = ROOT / "runs" / "b1-beta-inertness" / "ledger.json"
OUT = ROOT / "experiments" / "b1-beta-inertness" / "RESULTS.md"
ARMS = ("decoupled_wd", "phi_clip", "joint_clip", "coupled_l2")
EPS = ("1e-08", "1e-12")
BETAS = ("0.01", "0.1", "1")


def g(x, p=3):
    if x is None:
        return "—"
    if isinstance(x, bool):
        return str(x)
    if isinstance(x, int):
        return str(x)
    if x == 0:
        return "0"
    return f"{x:.{p}g}"


def traj(v, s, arm: str, e: str, snap: str) -> str:
    c = v(f"cmp.seed{s}.{arm}.eps{e}.beta0.01")[snap]
    return f"{g(c['rel'], 2)} ({g(c['agreement'], 4)})"


def rows_of(doc: dict) -> dict:
    return {r["key"]: r for r in doc["rows"]}


def render(doc: dict) -> str:
    R = rows_of(doc)
    v = lambda k: R[k]["value"]  # noqa: E731
    seeds = doc["seeds_actually_run"]
    prov = doc["provenance"]
    out = [
        "# B1: β inertness at real scale — RESULTS",
        "",
        "<!-- GENERATED by experiments/b1-beta-inertness/results_report.py from "
        "runs/b1-beta-inertness/ledger.json. Do not edit: regenerate. -->",
        "",
        "**Written by a model** (Claude Opus 5.5, `rsr-researcher`), generated from the "
        "ledger. **Not written by Brendan.** MEASURE-THEN-DECIDE: evidence for ADR-0009 "
        "L7 and L8, not a decision; no ADR, correction or registry entry is touched.",
        "",
        "## Provenance",
        "",
        "| | |",
        "|---|---|",
        "| PREREG | `experiments/b1-beta-inertness/PREREG.md` @ a0c2b30 |",
        f"| Command | `{doc['commands'][-1]['argv']}` "
        f"(exit {doc['commands'][-1]['exit_code']}) |",
        f"| Git SHA | `{prov.get('git_sha')}` (dirty: {prov.get('dirty')}) |",
        f"| Config hash | `{doc['config_hash']}` (manifest written "
        f"{doc['manifest_written_utc']}) |",
        f"| Hardware | {prov.get('platform')}, {prov.get('machine')}, device "
        f"`{doc['device']}`, Python {prov.get('python')} |",
        f"| Seeds actually run | {seeds}; steps {doc['steps_done']} of "
        f"{doc['steps_requested']} |",
        f"| Status / verdict | `{doc['status']}` / `{doc['verdict']['outcome']}` |",
        f"| Wall | {g(v('wall_seconds'), 4)} s; peak RSS {g(v('peak_rss_gb'))} GB |",
        f"| T0 start / end | ok={v('T0.start')['ok']} n={v('T0.start').get('n')} / "
        f"ok={v('T0.end')['ok']} n={v('T0.end').get('n')} |",
        f"| VOID reasons | {v('void') or 'none'} |",
        "",
        "## Real-scale inputs (ledger `data.seed{s}`)",
        "",
        "| seed | d | train rows | decisions | G on rows: mean / sd / min / max | "
        "‖s‖ range | ‖c‖ range | g_T median (min-max) | capture s |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for s in seeds:
        d = v(f"data.seed{s}")
        G = d["G_rows"]
        out.append(
            f"| {s} | {d['d']} | {d['n_train_rows']} | {d['n_decisions']} | "
            f"{g(G['mean'])} / {g(G['sd'])} / {g(G['min'])} / {g(G['max'])} | "
            f"{g(d['gest_norm']['min'], 4)}-{g(d['gest_norm']['max'], 4)} | "
            f"{g(d['ctx_norm']['min'], 4)}-{g(d['ctx_norm']['max'], 4)} | "
            f"{g(d['g_T']['median'])} ({g(d['g_T']['min'])}-{g(d['g_T']['max'])}) | "
            f"{g(d['capture_seconds'], 4)} |"
        )
    out += [
        "",
        "## The classification (PREREG §7; ledger `class.<arm>.eps<ε>`)",
        "",
        "INERT: min agreement ≥ 0.99 and max rel ≤ 0.01; LIVE: min agreement < 0.95 or "
        "max rel > 0.10; over β ∈ {0.01, 0.1} x every seed, at step 3000.",
        "",
        "| arm | ε | class | min argmin agreement | max rel max\\|Δφ\\| |",
        "|---|---|---|---|---|",
    ]
    for arm in (*ARMS, "P"):
        for e in EPS:
            c = v(f"class.{arm}.eps{e}")
            out.append(
                f"| {arm} | {e} | **{c['class']}** | {g(c['min_agreement'], 5)} | "
                f"{g(c['max_rel'])} |"
            )
    out += [
        "",
        "## Per-arm table: β x arm x ε (step 3000; each cell is seeds "
        + ", ".join(str(s) for s in seeds)
        + ")",
        "",
        "Against β = 1 of the same seed, arm and ε (ledger `cmp.seed{s}.<arm>.eps<ε>."
        "beta<β>` at key `3000`). ε/√v̂ from ledger `run.seed{s}.<arm>.eps<ε>.beta<β>`.",
        "",
        "| arm | ε | β | agreement | rel max\\|Δφ\\| | max\\|Δφ\\| | ε/√v̂ p50 | "
        "ε/√v̂ p99 | ε/√v̂ max | frac ε/√v̂ > 0.01 | ‖∇L_MC‖ @3000 | extra |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]

    def per_seed(fn):
        return " / ".join(fn(s) for s in seeds)

    for arm in (*ARMS, "P"):
        for e in EPS:
            for b in BETAS:
                if arm == "P" and b == "1":
                    continue
                rk = lambda s: f"run.seed{s}.{arm}.eps{e}.beta{b}"  # noqa: E731
                ck = lambda s: f"cmp.seed{s}.{arm}.eps{e}.beta{b}"  # noqa: E731
                if b == "1":
                    agr = rel = mab = "(ref)"
                else:
                    agr = per_seed(lambda s: g(v(ck(s))["3000"]["agreement"], 5))
                    rel = per_seed(lambda s: g(v(ck(s))["3000"]["rel"]))
                    mab = per_seed(lambda s: g(v(ck(s))["3000"]["max_abs"]))
                er = lambda s, q: g(v(rk(s))["eps_ratio"][q], 2)  # noqa: E731
                gn = per_seed(lambda s: g(v(rk(s))["grad_norm_unscaled"]["3000"]))
                extra = ""
                if arm == "phi_clip":
                    extra = "clip frac " + per_seed(lambda s: g(v(rk(s))["clip_frac"]))
                if arm == "joint_clip":
                    extra = "m4 dev max " + per_seed(
                        lambda s: g(v(rk(s))["joint_dev"]["max"], 2)
                    )
                    extra += "; median " + per_seed(
                        lambda s: g(v(rk(s))["joint_dev"]["median"], 2)
                    )
                out.append(
                    f"| {arm} | {e} | {b} | {agr} | {rel} | {mab} | "
                    f"{per_seed(lambda s: er(s, 'p50'))} | "
                    f"{per_seed(lambda s: er(s, 'p99'))} | "
                    f"{per_seed(lambda s: er(s, 'max'))} | "
                    f"{per_seed(lambda s: er(s, 'frac_gt_0.01'))} | {gn} | {extra} |"
                )
    out += [
        "",
        "## Trajectory: rel max|Δφ| and agreement by step (β = 0.01; seeds "
        + ", ".join(str(s) for s in seeds)
        + ")",
        "",
        "| arm | ε | 100 | 300 | 1000 | 3000 |",
        "|---|---|---|---|---|---|",
    ]
    for arm in (*ARMS, "P"):
        for e in EPS:
            cells = []
            for snap in ("100", "300", "1000", "3000"):
                cells.append(per_seed(lambda s: traj(v, s, arm, e, snap)))
            out.append(f"| {arm} | {e} | " + " | ".join(cells) + " |")
    out += [
        "",
        "Each entry is rel max|Δφ| (argmin agreement).",
        "",
        "## Controls",
        "",
        f"- **N** (β = 1 re-run, must be bit-identical): ledger `N_ok` = "
        f"**{v('N_ok')}**; per seed max|Δφ| / agreement: "
        + per_seed(
            lambda s: (
                f"{g(v(f'cmp.seed{s}.N')['max_abs'])} / "
                f"{g(v(f'cmp.seed{s}.N')['agreement'])}"
            )
        ),
        "- **P** (β as φ's LR multiplier, must be LIVE): see the classification table.",
        "- **I** (a different φ init, context only): max|Δφ| / rel / agreement per seed: "
        + per_seed(
            lambda s: (
                f"{g(v('I_context')[f'seed{s}']['max_abs'])} / "
                f"{g(v('I_context')[f'seed{s}']['rel'])} / "
                f"{g(v('I_context')[f'seed{s}']['agreement'], 4)}"
            )
        ),
        "",
        "## Verdict row (ledger `verdict`)",
        "",
        f"- falsifier: {doc['verdict']['falsifier']}",
        f"- outcome: `{doc['verdict']['outcome']}`",
        f"- detail: {doc['verdict']['detail']}",
        "",
        "The ledger's `outcome` maps PREREG §1's sentence mechanically: `falsified` iff "
        "decoupled_wd at ε = 1e-8 is LIVE, `survived` iff it is INERT, else "
        "`inconclusive`. It is not a decision on L7 or L8.",
        "",
    ]
    return "\n".join(out)


def main() -> Exit:
    if not LEDGER.exists():
        return did_not_run(f"no ledger at {LEDGER}")
    doc = json.loads(LEDGER.read_text())
    OUT.write_text(render(doc))
    print(f"wrote {OUT}")
    return Exit.OK


if __name__ == "__main__":
    run_main(main)
