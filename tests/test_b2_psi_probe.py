def _one_step(tiny):
    model = tiny["model"]
    doc = tiny["eval"][0]
    ids, mask = encode([doc], tiny["vmap"], max_tokens=TL, steps=TS)
    return model, ids, mask


def test_the_logit_prehook_does_not_change_the_forward(b2, tiny):
    model, ids, mask = _one_step(tiny)
    lens = torch.full((1,), TS)
    outs_a, outs_b = [], []

    def sf(sink):
        def f(t, out, ids_t, mask_t, row_valid):
            sink.append((out.logits.clone(), out.srep.clone()))
            return torch.zeros(())

        return f

    with torch.no_grad():
        run_policy_loop(model, ids, mask, lens, FIFOPolicy(), step_fn=sf(outs_a))
        hook = b2.LogitHook(model)
        try:
            run_policy_loop(
                model, ids, mask, lens, FIFOPolicy(), step_fn=sf(outs_b), capture=True
            )
        finally:
            hook.remove()
    for (la, sa), (lb, sb) in zip(outs_a, outs_b, strict=True):
        assert torch.equal(la, lb) and torch.equal(sa, sb)
    assert len(hook.calls) == TS * len(model.cfg.cross_attention_layers)


def test_recomputed_logits_softmax_to_the_captured_alpha(b2, tiny):
    model, ids, mask = _one_step(tiny)
    lens = torch.full((1,), TS)
    worst = []

    with torch.no_grad():
        hook = b2.LogitHook(model)

        def f(t, out, ids_t, mask_t, row_valid):
            lg = hook.take()
            worst.append(b2.logit_control(lg, out.cross_attention, mask_t))
            return torch.zeros(())

        try:
            run_policy_loop(model, ids, mask, lens, FIFOPolicy(), step_fn=f, capture=True)
        finally:
            hook.remove()
    assert max(worst[1:]) <= b2.LOGIT_TOL  # step 0 has an empty memory


