    out = b2.paired_bootstrap(per, {"a_minus_rand": ("a", "random")}, seed=0, n_boot=50)
    rand_acc = sum(float(per[f"random{k}"][:, 1].sum() / n.sum()) for k in range(5)) / 5
    assert out["a_minus_rand"]["point"] == pytest.approx(1.0 - rand_acc)
    assert "sd" in out["a_minus_rand"]
    # the generator is seeded 20260927 + seed
    assert b2.BOOT_SEED_BASE == 20260927


