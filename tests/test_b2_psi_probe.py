def test_the_probe_evicts_the_argmin_ties_to_the_oldest_and_logs_it(b2):
    doc = _tiny_docs([940000])[0]
    d = 2
    # w picks psi = u_s . s with u_s = (1, 0): scores are the first coordinate
    w = torch.zeros(b2.p_of(d), dtype=torch.float64)
    w[d * d] = 1.0
    pol = b2.ProbeArgminPolicy(w, "bilinear", doc=doc, model_seed=2, arm="U", S=TS)
    g = torch.tensor([[0.5, 0.0], [0.1, 9.0], [0.1, -9.0], [0.7, 0.0]])
    st = _state(g, [3, 4, 5, 6], 7)
    k = pol.select_eviction(st, torch.zeros(d), 7)
    assert k == 1  # 0.1 twice: the lower slot index
    rec = pol.log[-1]
    assert rec["victim_slot"] == 1 and rec["written_at"] == 4 and rec["age"] == 3
    assert rec["rank"] == 2 and rec["rank_shift"] == [2, 1]
    assert rec["margin"] == pytest.approx(0.0)
    assert rec["psi"] == pytest.approx([0.5, 0.1, 0.1, 0.7])
    assert rec["doc"] == doc.doc_id and rec["seed"] == 2 and rec["arm"] == "U"
    assert rec["kind"] in ("assert", "query", "filler")


