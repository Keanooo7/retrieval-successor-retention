def test_kind_oracle_ties_are_uniform_random_seeded_per_step(b2):
    """A1.10: ties inside the lowest class are broken by
    random.Random(f"ko:{seed}:{doc_id}:{t}"), never by age."""
    doc = _tiny_docs([940001])[0]
    means = {"assert": 1.0, "query": 1.0, "filler": 1.0}  # everything ties
    picks = []
    for t in range(20, 60):
        pol = b2.KindOracle(means, doc=doc, model_seed=1, tie="random", S=TS)
        st = MemoryState(
            gestalts=torch.zeros(4, 1),
            written_at=torch.tensor([0, 1, 2, 3]),
            live=torch.ones(4, dtype=torch.bool),
            step=t,
        )
        k = pol.select_eviction(st, torch.zeros(1), t)
        rng = random.Random(f"ko:1:{doc.doc_id}:{t}")
        assert k == rng.choice([0, 1, 2, 3])
        picks.append(k)
    assert len(set(picks)) > 1  # not the oldest every time
    old = b2.KindOracle(means, doc=doc, model_seed=1, tie="oldest", S=TS)
    assert old.select_eviction(st, torch.zeros(1), 30) == 0


